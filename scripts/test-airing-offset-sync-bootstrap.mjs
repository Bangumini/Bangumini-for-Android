import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
import React from "react";
import TestRenderer, { act } from "react-test-renderer";
const root = new URL("../", import.meta.url);
const directory = await mkdtemp(join(tmpdir(), "offset-sync-bootstrap-"));
const url = name => pathToFileURL(join(directory, name)).href;
await writeFile(join(directory, "external.mjs"), `
import React from ${JSON.stringify(import.meta.resolve("react"))};
export const auth={checking:true,loggedIn:false,username:''};
export const useAuth=()=>auth;
const initial={account:null,ready:false,configured:false,autoSync:false,phase:'idle',conflicts:[],lastSyncedAt:null,error:null};
let state=initial;const listeners=new Set();
export const calls=[];export const activeCalls=[];
export const publish=patch=>{state={...state,...patch};for(const listener of listeners)listener();};
export const offsetSync={getSnapshot:()=>state,subscribe:listener=>{listeners.add(listener);return()=>listeners.delete(listener);},setAccount:async account=>{calls.push(account);},setAppActive:value=>activeCalls.push(value)};
export const events={onChange:null,removed:false};
export const AppState={currentState:'active',addEventListener:(name,listener)=>{events.onChange=listener;return{remove:()=>{events.removed=true;events.onChange=null;}};}};
export const View=props=>React.createElement('View',props);
export const StyleSheet={create:value=>value,absoluteFillObject:{position:'absolute',top:0,left:0,right:0,bottom:0}};
export const colors={background:'#000'};
export const LoadingState=props=>React.createElement('LoadingState',props);
export const ErrorState=props=>React.createElement('ErrorState',props);
`);
async function compile(path,name,replacements){
 let source=await readFile(new URL(path,root),'utf8');
 for(const [from,to] of Object.entries(replacements))source=source.replaceAll(JSON.stringify(from),JSON.stringify(to));
 const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}}).outputText.replaceAll('"react/jsx-runtime"',JSON.stringify(import.meta.resolve('react/jsx-runtime')));
 await writeFile(join(directory,name),compiled);
}
await compile('src/hooks/useAiringOffsetSync.ts','hook.mjs',{'react':import.meta.resolve('react'),'../api/airing-offset-sync':url('external.mjs')});
await compile('src/components/AiringOffsetSyncBootstrap.tsx','bootstrap.mjs',{'react':import.meta.resolve('react'),'react-native':url('external.mjs'),'../api/airing-offset-sync':url('external.mjs'),'../hooks/useAiringOffsetSync':url('hook.mjs'),'../hooks/useAuth':url('external.mjs'),'./ScreenState':url('external.mjs'),'../theme/colors':url('external.mjs')});
const {default:Bootstrap}=await import(url('bootstrap.mjs'));
const {auth,publish,calls,activeCalls,events}=await import(url('external.mjs'));
let renderer,mounts=0,unmounts=0;
function ProtectedPage(){React.useEffect(()=>{mounts++;return()=>{unmounts++;};},[]);return React.createElement('ProtectedPage');}
const render=()=>React.createElement(Bootstrap,null,React.createElement(ProtectedPage));
const isHidden=()=>renderer.root.findByProps({testID:'offset-sync-content'}).props.accessibilityElementsHidden;
await act(async()=>{renderer=TestRenderer.create(render());});
assert.equal(mounts,1,'恢复偏置时必须保留导航挂载，不能让登录跳转落在已卸载的Stack上');
assert.equal(isHidden(),true,'首屏不能使用未知账号的偏置');
const hidden=renderer.root.findByProps({testID:'offset-sync-content'}).props;
assert.equal(hidden.pointerEvents,'none');assert.equal(hidden.importantForAccessibility,'no-hide-descendants');
assert(hidden.style.some(style=>style?.opacity===0),'遮罩期间也要隐藏旧页面像素');
await act(async()=>{auth.checking=false;auth.loggedIn=true;auth.username='alice';renderer.update(render());});
assert.deepEqual(calls,['alice']);
assert.equal(isHidden(),true);
await act(async()=>publish({account:'alice',ready:true,phase:'syncing'}));
assert.equal(isHidden(),false,'只等待本地恢复，不等待网络');
await act(async()=>{auth.checking=true;auth.username='bob';renderer.update(render());});
assert.equal(isHidden(),true,'认证中已变账号也不能显示上一账号的页面');
await act(async()=>{auth.checking=false;renderer.update(render());});
assert.equal(isHidden(),true,'Bob首帧不能展示仍属于Alice的本地偏置');
await act(async()=>publish({account:'bob',ready:false,phase:'error',error:'本机读取失败'}));
assert.equal(renderer.root.findAllByType('ErrorState').length,1);
await act(async()=>{renderer.root.findByType('ErrorState').props.onRetry();});
assert.equal(calls.at(-1),'bob');
await act(async()=>publish({account:'bob',ready:true,phase:'idle'}));
assert.equal(isHidden(),false);
await act(async()=>{auth.checking=true;renderer.update(render());});
assert.equal(isHidden(),false,'原账号刷新认证状态不应遮挡整个导航');
await act(async()=>{events.onChange('background');events.onChange('active');});
assert.deepEqual(activeCalls.slice(-2),[false,true]);
await act(async()=>{auth.checking=false;auth.loggedIn=false;auth.username='';renderer.update(render());});
assert.equal(isHidden(),true,'登出不能短暂显示已退出账号偏置');
await act(async()=>publish({account:null,ready:true,phase:'idle'}));
assert.equal(isHidden(),false);
await act(async()=>renderer.unmount());
assert.equal(events.removed,true);assert.equal(activeCalls.at(-1),false);
assert.equal(mounts,1,'切账号、失败重试及登出不能重建导航');assert.equal(unmounts,1);
console.log('offset sync bootstrap: 本地账号屏障、网络非阻塞与前后台生命周期通过 ✓');
